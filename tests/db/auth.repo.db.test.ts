describe("auth on the postgres path never exposes bound parameters", () => {
  let pg: Db;
  beforeEach(async () => {
    pg = await freshDb();
  }, DB_HOOK_TIMEOUT);
  afterEach(() => closeDb(pg));

  it("Drizzle's 'Failed query ... params:' text never reaches DbError, the service or the logs", async () => {
    const repo = drizzleAuthRepo(drizzle({ client: pg, schema }) as unknown as Database);
    const secret = "scrypt$v1$secret-salt$secret-hash";
    // A NOT NULL/FK failure whose statement binds the hash and the token hash.
    const failure = await repo.insertSession({ user_id: U, token_hash: secret, expires_at: "2026-10-11T00:00:00.000Z" }).then(
      () => null,
      (error: unknown) => error,
    );
    expect(failure).toBeInstanceOf(DbQueryError);
    const normalized = (failure as DbQueryError).error;
    expect(normalized.code).toBe("23503");
    expect(normalized.message).not.toMatch(/Failed query|params:/);
    expect(normalized.message).not.toContain(secret);
    expect((failure as DbQueryError).message).not.toContain(secret);

    const wrapper = Object.assign(new Error(`Failed query: insert ...\nparams: ${secret}`), { params: [secret] });
    expect(JSON.stringify(toDbError(wrapper))).not.toContain(secret);
    expect(toDbError(wrapper).message).toBe("Database query failed.");

    const rpc = await repo
      .changeUserPassword({ userId: U, passwordHash: secret, currentTokenHash: secret, expectedPasswordHash: secret })
      .then(() => null, (error: unknown) => error as DbQueryError);
    expect(rpc?.error).toEqual({ code: "P0001", message: "USER_NOT_FOUND", details: null });
  });

  it("the service maps it to the generic INTERNAL error and logs nothing secret", async () => {
    engine.pg = pg;
    vi.stubEnv("DB_ENGINE", "postgres");
    vi.stubEnv("DATABASE_URL", "postgres://unused.invalid/db");
    const logs = [vi.spyOn(console, "error").mockImplementation(() => {}), vi.spyOn(console, "warn").mockImplementation(() => {})];
    try {
      const auth = await import("@/src/features/auth/service");
      await pg.exec(`ALTER TABLE public.sessions ADD CONSTRAINT no_sessions CHECK (false)`);
      const hash = await auth.hashPassword("Clave123");
      await pg.query(`INSERT INTO public.users (sede_id, id_type, id_number, password_hash, full_name) VALUES (${SEDE_ROW}, 'CC', 'sec-1', $1, 'Ana')`, [hash]);
      const error = await auth.loginWithDocument({ documento: "sec-1", password: "Clave123" }).then(() => null, (reason: unknown) => reason as Error);
      expect(error).toMatchObject({ code: "INTERNAL", status: 500, message: "Error interno." });
      const logged = JSON.stringify(logs.flatMap((spy) => spy.mock.calls));
      expect(logged).not.toContain(hash);
      expect(logged).not.toMatch(/params:/);
    } finally {
      for (const spy of logs) spy.mockRestore();
      vi.unstubAllEnvs();
    }
  });
});
