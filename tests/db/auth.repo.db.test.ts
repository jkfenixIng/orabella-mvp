/**
 * Auth: equivalence of the two engines over the real schema.
 *
 * 1. Repository level: supabase-js (PostgREST double) ↔ Drizzle, same seed.
 * 2. Service level: the SAME service flows run once per engine — the
 *    `supabase` engine through the double, the `postgres` engine through
 *    Drizzle (getDb() replaced by a PGlite instance) — and must observe the
 *    same database state: login, sessions, expiry, revocation, the password
 *    change CAS, the reset token, user creation with its role, and the Auth
 *    mirror (kept on supabase, omitted on postgres).
 * 3. Security: an auth SQL error on the postgres path never carries the
 *    bound parameters (password hash, token hash) to the service or the logs.
 */
import { drizzle } from "drizzle-orm/pglite";
import { afterEach, beforeAll, beforeEach, describe, expect, it, vi } from "vitest";
import { drizzleAuthRepo } from "@/src/features/auth/repos/auth.drizzle";
import { supabaseAuthRepo, type AuthRepo } from "@/src/features/auth/repos/auth";
import type { Database } from "@/src/shared/db/client";
import { DbQueryError, toDbError } from "@/src/shared/db/errors";
import * as schema from "@/src/shared/db/schema";
import { DB_HOOK_TIMEOUT, closeDb, freshDb, warmTemplate, type Db } from "./harness";
import { postgrestDouble, type AuthAdminDouble } from "./postgrest-double";

const engine = vi.hoisted(() => ({
  pg: null as unknown as Db,
  mirror: [] as Array<Record<string, unknown>>,
  mirrorError: null as null | { code: string; message: string },
}));

const authAdmin: AuthAdminDouble = {
  async createUser(values) {
    engine.mirror.push(values);
    return engine.mirrorError ? { data: null, error: engine.mirrorError } : { data: { user: { id: "auth-1" } }, error: null };
  },
};

vi.mock("@/src/shared/lib/supabase/server", async () => {
  const { postgrestDouble: double } = await import("./postgrest-double");
  return {
    createAdminClient: () => {
      // With DB_ENGINE=postgres there is no Supabase: any attempt to use it
      // (auth, audit...) fails the test instead of silently writing elsewhere.
      if (process.env.DB_ENGINE === "postgres") throw new Error("Supabase client used with DB_ENGINE=postgres");
      return double(engine.pg, authAdmin);
    },
  };
});
vi.mock("@/src/shared/db/client", async () => {
  const { drizzle: wrap } = await import("drizzle-orm/pglite");
  const tables = await import("@/src/shared/db/schema");
  return { getDb: () => wrap({ client: engine.pg, schema: tables }) };
});

